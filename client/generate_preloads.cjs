        'minigun': 'bullet_minigun',
        'unfail_minigun': 'bullet_minigun',
        'air_minigun': 'bullet_minigun',
        'laser_pistol': 'laser',
        'laser_pistol2': 'laser',
        'laser_rifle': 'laser',
