const weaponsMatch = weaponsFile.match(/export const WEAPONS: Record<WeaponType, WeaponConfig> = ({[\s\S]+});/);

if (!weaponsMatch) {
    process.exit(1);
}

const keys = [];
const regex = /"([^"]+)": {/g;
let match;
while ((match = regex.exec(weaponsMatch[1])) !== null) {
    keys.push(match[1]);
}

